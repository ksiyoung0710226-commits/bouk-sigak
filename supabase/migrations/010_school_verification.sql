-- 학교·학과 검증
-- 재학생이 고른 학교+학과가 공식 학과 목록(school_majors)에 있으면 school_verified = true (DB가 판단, 회원이 직접 못 바꿈)

create table public.school_majors (
  school text not null,
  major text not null,
  region text,
  school_type text,
  primary key (school, major)
);
alter table public.school_majors enable row level security;
create policy school_majors_read on public.school_majors for select to anon, authenticated using (true);
revoke insert, update, delete on public.school_majors from anon, authenticated;

alter table public.profile_details add column major text check (major is null or char_length(major) between 1 and 50);
alter table public.profile_details add column school_verified boolean not null default false;

create function public.verify_school() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.school := nullif(btrim(new.school), '');
  new.major := nullif(btrim(new.major), '');
  new.school_verified := new.school is not null and new.major is not null
    and exists (select 1 from public.school_majors where school = new.school and major = new.major);
  return new;
end $$;
create trigger profile_details_verify_school
before insert or update on public.profile_details
for each row execute function public.verify_school();
revoke execute on function public.verify_school() from public, anon, authenticated;

-- 회원이 쓸 수 있는 칸에 major 추가 (school_verified는 트리거만 바꿈)
grant insert (major) on public.profile_details to authenticated;
grant update (major) on public.profile_details to authenticated;

-- 가입 트리거: major도 저장
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  k text := case when m->>'kind' = 'teacher' then 'teacher' else 'student' end;
  v_school text := left(nullif(btrim(m->>'school'), ''), 50);
  v_major text := left(nullif(btrim(m->>'major'), ''), 50);
  v_region text := nullif(m->>'region', '');
  v_center text := nullif(m->>'center_type', '');
begin
  insert into public.profiles (id, nickname, kind)
  values (new.id, left(coalesce(nullif(trim(m->>'nickname'), ''), '익명'), 20), k);

  if v_region not in ('서울','부산','대구','인천','광주','대전','울산','세종','경기','강원','충북','충남','전북','전남','경북','경남','제주') then
    v_region := null;
  end if;
  if v_center not in ('국공립','사회복지법인','법인·단체등','민간','가정','협동','직장','기타') then
    v_center := null;
  end if;

  insert into public.profile_details (user_id, school, major, region, center_type, is_public)
  values (
    new.id,
    case when k = 'student' then v_school end,
    case when k = 'student' then v_major end,
    case when k = 'teacher' then v_region end,
    case when k = 'teacher' then v_center end,
    coalesce((m->>'info_public')::boolean, true)
  );
  return new;
end $$;
revoke execute on function public.handle_new_user() from anon, authenticated, public;

-- 관리자 회원 목록에 학과·검증 여부 추가
drop function public.admin_list_members();
create function public.admin_list_members()
returns table (
  id uuid, email text, nickname text, kind text, teacher_verified boolean, is_admin boolean,
  created_at timestamptz, last_sign_in_at timestamptz, post_count bigint, comment_count bigint,
  school text, major text, school_verified boolean, region text, center_type text, info_public boolean
)
language plpgsql stable security definer set search_path = public, auth as $$
begin
  if not public.is_admin() then
    raise exception 'admin only';
  end if;
  return query
    select p.id, u.email::text, p.nickname, p.kind, p.teacher_verified, p.is_admin,
           p.created_at, u.last_sign_in_at,
           (select count(*) from public.posts po where po.author_id = p.id),
           (select count(*) from public.comments c where c.author_id = p.id),
           d.school, d.major, coalesce(d.school_verified, false), d.region, d.center_type, coalesce(d.is_public, true)
    from public.profiles p
    join auth.users u on u.id = p.id
    left join public.profile_details d on d.user_id = p.id
    order by p.created_at desc;
end $$;
revoke execute on function public.admin_list_members() from public, anon;
grant execute on function public.admin_list_members() to authenticated;

